#!/usr/bin/env python3
"""Renders the UNIT808 vector kit (assets/ui_src) to 2x PNGs (assets/ui) and writes
Source/Layout.h from control_layout.json.  Run again whenever the artwork changes:

    python3 tools/rasterise_ui.py
"""
import json, re
from pathlib import Path
from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parent.parent
SRC, OUT = ROOT / "assets" / "ui_src", ROOT / "assets" / "ui"
SCALE = 2
OUT.mkdir(parents=True, exist_ok=True)

def png_name(stem): return stem.replace("-", "_") + ".png"

def viewbox(svg):
    m = re.search(r'viewBox="([^"]+)"', svg)
    return [float(v) for v in m.group(1).replace(",", " ").split()]

jobs = [("faceplate", (SRC / "TR808_faceplate.svg").read_text()), ("brand", (SRC / "brand.svg").read_text())] + [(n, (SRC / f"{n}.svg").read_text()) for n in ("trimmer_body", "trimmer_face", "trimmer_slot")]
for f in sorted((SRC / "assets").glob("*.svg")):
    jobs.append((f.stem, f.read_text()))

boxes = {}
with sync_playwright() as p:
    b = p.chromium.launch()
    for stem, svg in jobs:
        x, y, w, h = viewbox(svg)
        boxes[stem] = (x, y, w, h)
        svg = re.sub(r'<svg([^>]*?)\swidth="[^"]*"', r'<svg\1', svg, count=1)
        svg = re.sub(r'<svg([^>]*?)\sheight="[^"]*"', r'<svg\1', svg, count=1)
        svg = svg.replace("<svg", f'<svg width="{w}" height="{h}"', 1)
        page = b.new_page(viewport={"width": int(round(w)), "height": int(round(h))}, device_scale_factor=SCALE)
        page.set_content(f'<html><body style="margin:0;background:transparent">{svg}</body></html>')
        page.screenshot(path=str(OUT / png_name(stem)), omit_background=True,
                        clip={"x": 0, "y": 0, "width": w, "height": h})
        page.close()
    b.close()

# the board inside is a photo, cleaned up and silkscreened by tools/make_board.py (JPEG, 2x)
import subprocess, sys
subprocess.run([sys.executable, str(ROOT / "tools" / "make_board.py")], check=True)
boxes["board"] = (0.0, 0.0, 1870.0, 1090.0)

# ---------------------------------------------------------------- Layout.h
L = json.loads((SRC / "control_layout.json").read_text())
cw, ch = L["canvas"]["width"], L["canvas"]["height"]
lines = ["// Generated by tools/rasterise_ui.py from assets/ui_src/control_layout.json - do not edit.",
         "#pragma once", "namespace unit808ui {",
         f"constexpr float kPanelW = {cw}.0f, kPanelH = {ch}.0f;",
         f"constexpr float kImageScale = {SCALE}.0f;",
         "struct Art { const char* res; float x, y, w, h; };   // BinaryData resource and its place on the panel"]
def art(stem):
    x, y, w, h = boxes[stem]
    return f'{{ "{png_name(stem).replace(".", "_")}", {float(x)}f, {float(y)}f, {float(w)}f, {float(h)}f }}'
lines.append(f"constexpr Art kFaceplate = {art('faceplate')};")
lines.append(f"constexpr Art kBrand = {art('brand')};")
lines.append(f"constexpr Art kBoard = {art('board').replace('board_png', 'board_jpg')};")
B = json.loads((SRC / "board_layout.json").read_text())
lines.append("struct Pad { const char* id; const char* label; float cx, cy, size; };   // trimmer pads on the board inside")
lines.append(f"constexpr int kNumPads = {len(B['pads'])};")
lines.append("constexpr Pad kPads[kNumPads] = {")
for pd in B["pads"]:
    lines.append(f'    {{ "{pd["id"]}", "{pd["label"].replace(chr(10), " ")}", {float(pd["cx"])}f, {float(pd["cy"])}f, {float(pd["size"])}f }},')
lines.append("};")
pl = B["plate"]
lines.append(f"constexpr float kPlateX = {float(pl['x'])}f, kPlateY = {float(pl['y'])}f, kPlateW = {float(pl['width'])}f, kPlateH = {float(pl['height'])}f;")
lines.append("struct Ctrl { const char* id; const char* type; float cx, cy, r, x, y, w, h; int positions; Art a[4]; int nDetents; float detents[12]; float defaultAngle; };")
ctrls = []
for c in L["controls"]:
    a = c.get("asset", {})
    keys = {"knob": ["base", "cap"], "switch": [f"pos{i}" for i in range(4)], "lever": [f"pos{i}" for i in range(3)],
            "button": ["up", "down"], "led": ["off", "on"]}[c["type"]]
    arts = [art(Path(a[k]).stem) for k in keys if k in a]
    while len(arts) < 4: arts.append('{ nullptr, 0, 0, 0, 0 }')
    det = c.get("detents", [])
    cx, cy, r = c.get("cx", 0), c.get("cy", 0), c.get("radius", 0)
    x, y, w, h = c.get("x", cx - r), c.get("y", cy - r), c.get("width", 2 * r), c.get("height", 2 * r)
    pos = c.get("positions", len(det) if det else 0)
    detstr = ", ".join(f"{float(d)}f" for d in det) or "0"
    F = lambda v: f"{float(v)}f"
    ctrls.append(f'    {{ "{c["id"]}", "{c["type"]}", {F(cx)}, {F(cy)}, {F(r)}, {F(x)}, {F(y)}, {F(w)}, {F(h)}, {pos}, {{ {", ".join(arts)} }}, {len(det)}, {{ {detstr} }}, {F(c.get("default_angle", 0))} }},')
lines.append(f"constexpr int kNumCtrls = {len(ctrls)};")
lines.append("constexpr Ctrl kCtrls[kNumCtrls] = {")
lines += ctrls
lines += ["};", "} // namespace unit808ui", ""]
(ROOT / "Source" / "Layout.h").write_text("\n".join(lines))
print(f"{len(jobs)} images -> {OUT}, {len(ctrls)} controls -> Source/Layout.h")
